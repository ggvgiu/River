DoSound:
; start with channel 0:
       LDY    #$1C              ; 2
       LDA    sound0Cnt         ; 3
       LDX    sound0Id          ; 3
       BEQ    LF789             ; 2
       DEX                      ; 2
       BEQ    LF770             ; 2
       LDY    #$0F              ; 2
       CPX    #$02              ; 2
       BCS    LF776             ; 2
       LDY    #$08              ; 2
LF770: LSR                      ; 2
       TAX                      ; 2
       LDA    #$08              ; 2             white noise
       BNE    LF77D             ; 2

LF776: BEQ    LF77A             ; 2
       LDY    #$1F              ; 2
LF77A: TAX                      ; 2
       LDA    #$04              ; 2             high pure tone
LF77D: DEC    sound0Cnt         ; 5
       BNE    .setAud0          ; 2
       PHA                      ; 3
       LDA    #0                ; 2
       STA    sound0Id          ; 3             stop sound0
       PLA                      ; 4
       BPL    .setAud0          ; 2

; low fuel sound:
LF789: LDA    gameMode          ; 3             game running?
       BNE    .mute0            ; 2              no, quiet (x=0)
       LDA    fuelHi            ; 3
       CMP    #$40              ; 2
       BCS    .jetSound         ; 2
       LDY    sound0Cnt         ; 3
       BNE    .contSound0       ; 2
       LDY    #$3F              ; 2
.contSound0:
       DEY                      ; 2
       STY    sound0Cnt         ; 3
       LDX    fuelLo            ; 3
       STX    temp              ; 3
       CMP    #$04              ; 2
       BCS    LF7B0             ; 2
       ROL    temp              ; 5
       ROL                      ; 2
       ROL    temp              ; 5
       ROL                      ; 2
       EOR    #$FF              ; 2
       ADC    #$20              ; 2
       BNE    .loadAud0         ; 2

LF7B0: CPY    #$1C              ; 2
       BCC    .jetSound         ; 2
       TYA                      ; 2
       LSR                      ; 2
.loadAud0:
       TAY                      ; 2
       LDA    #$0C              ; 2
       LDX    #$0F              ; 2
       BNE    .setAud0          ; 2

; make some noise, depending on jet speed:
.jetSound:
       LDA    speedY            ; 3             frequency depends on y-speed
       LSR                      ; 2
       LSR                      ; 2
       LSR                      ; 2
       LSR                      ; 2
       EOR    #$FF              ; 2
       SEC                      ; 2
       ADC    #$1F              ; 2
       TAY                      ; 2
       LDA    joystick          ; 3             volume depends on joystick position
       AND    #MOVE_UP|MOVE_DOWN; 2
       TAX                      ; 2
       LDA    VolumeTab,X       ; 4
       TAX                      ; 2
       LDA    #$08              ; 2             white noise
.setAud0:
       STA    AUDC0             ; 3
       STY    AUDF0             ; 3
.mute0:
       STX    AUDV0             ; 3

; continue with channel 1:
; (missile fire or bridge explosion)
       LDA    missileSound      ; 3
       BEQ    .noMissileSound   ; 2
       DEC    missileSound      ; 5
       LDX    bridgeSound       ; 3             bridge exposion has higher priority
       BNE    .doBridge         ; 2
       EOR    #$FF              ; 2
       SEC                      ; 2
       ADC    #$1C              ; 2
       LDY    #$0C              ; 2             medium pure tone
       LDX    #$08              ; 2
       BNE    .setAud1          ; 2

.noMissileSound:
       LDX    bridgeSound       ; 3
       BEQ    .skipSound1       ; 2
; let the bridge explode:
.doBridge:
       DEC    bridgeSound       ; 5             countdown volume
       TXA                      ; 2
       LSR                      ; 2
       CLC                      ; 2
       ADC    #$04              ; 2
       TAX                      ; 2
       LDA    random8           ; 3             random frequency
       ORA    #$18              ; 2
       LDY    #$08              ; 2
.setAud1:
       STA    AUDF1             ; 3
       STY    AUDC1             ; 3
.skipSound1:
       STX    AUDV1             ; 3

; start next frame:
.waitTim:
       LDA    INTIM             ; 4
       BNE    .waitTim          ; 2
       LDY    #$82              ; 2
       STY    WSYNC             ; 3             wait for sync; wait for TIA to finish line
       STY    VSYNC             ; 3
       STY    WSYNC             ; 3
       STY    WSYNC             ; 3
       STY    WSYNC             ; 3
       STA    VSYNC             ; 3
  IF NTSC
       LDA    #43               ; 2
  ELSE
       LDA    #73               ; 2
  ENDIF
       STA    TIM64T            ; 4

; *** check switches: ***
       LDA    SWCHB             ; 4
       LSR                      ; 2
       BCS    .noReset          ; 2
       LDA    gameVariation     ; 3             RESET was pressed
       STA    player            ; 3
       LDX    #$F7              ; 2
       JMP    Reset             ; 3

.noReset:
       LSR                      ; 2
       BCS    .noSelect         ; 2
       DEC    gameDelay         ; 5             SELECT was pressed
       BPL    .skipSelect       ; 2
       LDA    gameVariation     ; 3             toggle game (one or two player)
       EOR    #$01              ; 2
       STA    gameVariation     ; 3
  IF SCREENSAVER
       STA    SS_Delay          ; 3
  ELSE
       FILL_NOP 2
  ENDIF
       STA    player            ; 3
       ASL                      ; 2
       ASL                      ; 2
       ASL                      ; 2
       ADC    #DIGIT_H          ; 2
       JSR    SetScorePtrs      ; 6
       JSR    FinishGame        ; 6
       LDY    #$1E              ; 2
.noSelect:
       STY    gameDelay         ; 3

.skipSelect:
       LDA    gameMode          ; 3
       BMI    .mainLoopJmp      ; 2
       CMP    #SCROLL_STOP      ; 2             scrolling into game
       BNE    .scrollRiver      ; 2              no, generate new zones
       LDA    #<JetStraight-1   ; 2              yes, set..
       STA    shapePtr0         ; 3              ..jet data pointer..
.mainLoopJmp:
       JMP    MainLoop          ; 3              .. and continue with main loop

; calculate scroll lines by speedY, and
; check, if a new zone is neccessary:
.scrollRiver:
       LDA    #2                ; 2  $F85D      loop twice
       STA    zoneNum           ; 3             not zoneNum here but loop counter
.loopNext:
       DEC    zoneNum           ; 5             after looping twice
       BMI    .mainLoopJmp      ; 2              jump back to MainLoop
       LDA    speedY            ; 3
       CMP    #254              ; 2             speedY >= 254 (max speed)?
       BCS    .scrollOneLine    ; 2              yes, scroll one line (regardless of triggerY)
       ADC    triggerY          ; 3             A = speedY + triggerY
       STA    triggerY          ; 3             accumulate speedY
       BCC    .loopNext         ; 2              until it triggers > 255
.scrollOneLine:
       INC    zoneOffset        ; 5             scroll 1 line
       LDA    zoneOffset        ; 3
       CMP    #ZONE_LINES       ; 2             zoneOffset < ZONE_LINES (32)?
       BCC    .loopNext         ; 2              yes, room to loop again in this zone
; If speedY = 64 (slowest, 1/2 line per frame):
;   frame 1, loop 1: triggerY =  64
;   frame 1, loop 2: triggerY = 128
;   frame 2, loop 1: triggerY = 192
;   frame 2, loop 2: triggerY =   0 [scroll 1 line]
;   frame 3, loop 1: triggerY =  64
;   frame 3, loop 2: triggerY = 128
;   frame 4, loop 1: triggerY = 192
;   frame 4, loop 2: triggerY =   0 [scroll 1 line]
;   ...
; If speedY = 128 (cruise, 1 line per frame):
;   frame 1, loop 1: triggerY = 128
;   frame 1, loop 2: triggerY =   0 [scroll 1 line]
;   frame 2, loop 1: triggerY = 128
;   frame 2, loop 2: triggerY =   0 [scroll 1 line]
;   ...
; If speedY = 254 (fastest, 2 lines per frame):
;   frame 1, loop 1: triggerY = n/a [scroll 1 line]
;   frame 1, loop 2: triggerY = n/a [scroll 1 line]
;   frame 2, loop 1: triggerY = n/a [scroll 1 line]
;   frame 2, loop 2: triggerY = n/a [scroll 1 line]
;   ...
;
; If speedY = 106 (misc value, 0.828125 lines per frame ;):
;   frame 1, loop 1: triggerY = 106
;   frame 1, loop 2: triggerY = 212
;   frame 2, loop 1: triggerY = 318(62) [scroll 1 line]
;   frame 2, loop 2: triggerY = 168
;   frame 3, loop 1: triggerY = 274(18) [scroll 1 line]
;   frame 3, loop 2: triggerY = 124
;   frame 4, loop 1: triggerY = 230
;   frame 4, loop 2: triggerY = 336(80) [scroll 1 line]
;   ...
; Or, in other words, you accelerate/decelerate at 0.015625 lines per frame.

; *** it#s time to create a new zone: ***
       LDX    #0                ; 2
       STX    zoneOffset        ; 3
       LDY    #MAX_ZONES        ; 2
       STY    temp              ; 3             move 6 zones
       LDA    level             ; 3
       CMP    #5                ; 2             first four levels?
       BCC    .firstLevels      ; 2              yes, prevent small valley, increase padding
       LDY    #0                ; 2              no, allow all widths of valley, tight spacing
.firstLevels:
       STY    easyPadding       ; 3             0 = all widths allowed, 6 = wider widths and padding

; first move the other zones, to make space for the new one:
.loopBlocks:                    ;
       LDY    #5                ; 2             move 5 bytes
.loopMoveBlock:
       LDA    zoneLst+1,X       ; 4
       STA    zoneLst,X         ; 4
       INX                      ; 2
       DEY                      ; 2
       BNE    .loopMoveBlock    ; 2
       INX                      ; 2             skip one entry
       DEC    temp              ; 5
       BNE    .loopBlocks       ; 2

       STY    State1LstNew      ; 3             y=0!
       LDA    zoneLstNew        ; 3             clear variable (except PF_LTGREEN_FLAG)
       AND    #PF_LTGREEN_FLAG  ; 2
       STA    zoneLstNew        ; 3
       LDX    newBankWidth      ; 3             copy previous PF pattern id
       STX    prevBankWidth     ; 3

       DEC    zone              ; 5             second zone of block?
       BEQ    .nextBlock        ; 2              yes, next block
       LDX    block             ; 3
       DEX                      ; 2             first zone of last block of level?
       BNE    .notLast          ; 2              no, continue zone
; first zone of last block:
       STX    levelEnd          ; 3              yes, end of current level
       LDA    level             ; 3
       LSR                      ; 2             straight current level?
       LDA    #PF_ROAD_FLAG     ; 2                set road flag for drawing last block (road in second zone)
       BCS    .isStraight       ; 2              yes, dark green in NEXT level
       LDA    #PF_ROAD_FLAG|PF_LTGREEN_FLAG; 2   no, lighter green in NEXT level
.isStraight:
       STA    zoneLstNew        ; 3
.notLast:
       JSR    NextRandom16      ; 6             new random number for next zone of block
       JMP    .nextBlockPart    ; 3

.nextBlock:
; continue with a 'normal' block:
       DEC    block             ; 5             last block of level?
       BNE    .contLevel        ; 2              no, continue

;*************** New Level ***************
       JSR    SaveLevel         ; 6              yes, save variables..
       LDX    #BLOCKS           ; 2              ..and got next level
       STX    block             ; 3

.contLevel:
       JSR    NextRandom16      ; 6             new random number for next block
       LDX    block             ; 3
       DEX                      ; 2             last block of level?
       BNE    .notLastBlock     ; 2              no, skip

; Last block (MJJ: ??? are we setting width one step ahead ???)
       STX    bankFlags         ; 3             yes, bankFlags = 00
       LDA    #12               ; 2             bridge bank width (PF1Bank8 + PF2Bank12)
       BNE    .setNewBankWidth  ; 3

.notLastBlock:
; straight or jagged level?
       LDA    level             ; 3
       LSR                      ; 2             straight level? CF=1 for odd levels, straight levels
       LDA    #7                ; 2             bank width for all straight level blocks (PF1Bank7)
       BCS    .setNewBankWidth  ; 2              yes, set
; Straight level -> done with setting bank width

;--------------------------------------
; BEGIN Jagged level bank work
       LDA    bankFlags         ; 3
       DEX                      ; 2             penultimate block of jagged level?
       BNE    .notPenultimate   ; 2              no, skip

; penultimate block of jagged level
       CMP    #INVERT_FLAG|INVERT_NB_FLAG; 2    both flags set? in full island state?
       BEQ    .zeroBanks        ; 2              yes, branch to finish the island
       BNE    .normalBanks      ; 3              no, branch to create normal banks

.notPenultimate:
; Just one example of many possibilities (always starts at 00):
; 1st entry: 00 -> x% -> 00 (rand outer bank), y% -> 01 (zero banks)
; 2nd entry: 01 -> 11 (rand island bank)
; 3rd entry: 11 -> x% -> 11 (rand island bank), y% -> 10 (zero banks)
; 4th entry: 10 -> 00 (rand outer bank)
; 5th entry: 00 -> x% -> 00 (rand outer bank), y% -> 01 (zero banks)
; 6th entry: 00 -> x% -> 00 (rand outer bank), y% -> 01 (zero banks)
; 7th entry: 01 -> 11 (rand island bank)
; 8th entry: 11 -> x% -> 11 (rand island bank), y% -> 10 (zero banks)
; 9th entry: 11 -> x% -> 11 (rand island bank), y% -> 10 (zero banks)
; ...
       ASL                      ; 2
       EOR    bankFlags         ; 3             00 ^ 00 = 00
                                ;               01 ^ 10 = 11 (sets Negative flag)
                                ;               10 ^ 00 = 10 (sets Negative flag)
                                ;               11 ^ 10 = 01
       BMI    .firstAfterZeroBanks ; 2          branch if orig flags 01 or 10 (curr val 11xxxxxx or 10xxxxxxx)
       LDA    randomLo          ; 3             randomly exit normal or island banks
       AND    #%00110000        ; 2             ~75% odds of same state
       BNE    .contBanks        ; 2             if any bit match, continue with normal or island banks

.zeroBanks:
       LDA    bankFlags         ; 3
       AND    #INVERT_FLAG      ; 2             INVERT_FLAG set?  11? (10 [and 01] does not reach here)
       BNE    .wasIsland        ; 2              yes, 11, clear INVERT_NB_FLAG (flags now: 10)
       ORA    #INVERT_NB_FLAG   ; 2              no, 00, set INVERT_NB_FLAG (flags now: 01)
.wasIsland:
       STA    bankFlags         ; 3             islands only in full-width river,
       LDA    #0                ; 2              after and before one block of 0 banks
       BEQ    .setNewBankWidth  ; 3

.firstAfterZeroBanks:
       LDA    #INVERT_FLAG|INVERT_NB_FLAG; 2
       BIT    bankFlags         ; 3             INVERT_NB_FLAG set?  01? (11 [and 00] does not reach here)
       BVS    .islandBanks      ; 2              yes, 01, set INVERT_FLAG (flags now: 11)
.normalBanks:
       LDA    #0                ; 2              no, 10, clear INVERT_FLAG (flags now: 00)
.islandBanks:
       STA    bankFlags         ; 3
.contBanks:

; create new random bank width:
       LDY    #14               ; 2             Y = 14  (max normal bank width is 14)
       LDA    randomLo          ; 3             A = random nibble
       AND    #$0F              ; 2             A = 0..15
       CMP    #2                ; 2
       BCS    .minOk            ; 2             branch if A >= 2
       ADC    #2                ; 2              else A = 2 or 3  (don't make islands too skinny or rivers too wide)
.minOk:                         ;               A = 2..15
       BIT    bankFlags         ; 3             INVERT_FLAG set?
       BPL    .normalBank       ; 2             branch if normal bank
       DEY                      ; 2              else Y = 13  (island bank can't be as wide, need 3 pixels each side for jet)
.normalBank:
       LDX    easyPadding       ; 3             easyPadding = 0 or 6 (all widths or limited widths)
       BEQ    .allWidths        ; 2             branch if all bank widths allowed
       LDY    #8                ; 2              else Y = 8  (max bank width for early levels is 8, wider rivers)
.allWidths:
       STY    temp              ; 3             store Y for compare
       CMP    temp              ; 3 
       BCC    .setNewBankWidth  ; 2             branch if A < Y   (Y = 8, 13, or 14)
       LDA    temp              ; 3              else A = Y       (A = 8, 13, or 14)
; END Jagged level bank work
;--------------------------------------

;--------------------------------------
.setNewBankWidth:
       STA    newBankWidth      ; 3             A = 12 or 7 or 0 or 2..8 or 2..13,14
       LDY    #ZONES            ; 2             reset zone
       STY    zone              ; 3


; WARNING: Some highly compressed code coming up.
; This code feels to be a different style from much of the rest.
.nextBlockPart:
       LDA    prevBankWidth     ; 3             A = prev
       TAX                      ; 2             tx/copy A to X   (X = prev)
       SEC                      ; 2             set CF in prep for SBC
       SBC    newBankWidth      ; 3             A = prev - new
       STA    diffBankWidths    ; 3             store the difference between the two blocks
       BCS    .prevWider        ; 2             branch if prev >= new  (A,diff >= 0)

; new bank width is wider than prev             diff < 0, new > prev
       INC    diffBankWidths    ; 5             diff = diff + 1
       CPX    #SWITCH_PAGE_ID-1 ; 2             compare prevBankWidth to 9-1 (aka: prev - 8)
       LDX    newBankWidth      ; 3             X = new
       BCS    .fullPF1Bank8     ; 2             branch if prev >= 8  (aka: new > 9)
       CPX    #SWITCH_PAGE_ID   ; 2              else compare newBankWidth to 9 (aka: new - 9)
       BCC    .bank0to8         ; 2             branch if new < 9
; This section executes just before bridge
; (and probably other shifts from wide to narrow rivers).
; New is wider and greater than 9, prev is 7 or less,
; so set up the pointer to PF1Bank8 to start "7 or less" lines
; before PF1Bank8 to build slope from PF1 into PF2 sizes.
       LDA    #-1               ; 2 $F94B        else A = -1  (-1 = %11111111, also CF=1 from CPX)
       ADC    prevBankWidth     ; 3               A = -1 + 1 + prevBankWidth (weird, why not just LDA prev?)
       BPL    .slopedPF1Bank8   ; 3             branch no matter what
                                ;                prev < new, prev < 8, new >= 9; thus: prev <= 7 or new >= 9

.prevWider:
; prev bank width is wider or equal to new      prev >= new
       BEQ    .equalWidth       ; 2             branch if prev = new   (diff = 0)
       DEC    diffBankWidths    ; 5              else diff = diff - 1
.equalWidth:
       CPX    #SWITCH_PAGE_ID   ; 2             compare prev to 9   (prev - 9)
       BCS    .bank9up          ; 2             branch if prev >= 9

.bank0to8:
       JSR    GetPageFlag       ; 6             IN: X = wider of prev or new; OUT: A = 1 (or 0 when bank=0)
       JSR    SetZoneVars_PF    ; 6             find and set bank pattern pointer (assumes PF2)
       STA    PF1LstNew         ; 3             copy PF2LstNew to PF1LstNew
       LDA    #<PFxBank0        ; 2             #0
       STA    PF2LstNew         ; 3             point PF2LstNew to the zero bank non-pattern
       BEQ    .finishBanks      ; 3

.bank9up:
       LDA    newBankWidth      ; 3
       CMP    #SWITCH_PAGE_ID-1 ; 2             compare new to 9-1   (new - 8)
       BCS    .fullPF1Bank8     ; 2             branch if new >= 8
; Setup PF1Lst ptr to move into PF1Bank8 to pick up slope at end
; after a few lines, for banks falling in size from PF2 to PF1.
       LDA    #<PF1Bank8+8      ; 2             #15  (NOTE: CF=0 thus next SBC will steal 1 to set CF!)
       SBC    newBankWidth      ; 3 $F96F       A = 15 - 0..7 - 1 = 7..14  (CF=1)
       BCS    .slopedPF1Bank8   ; 3             always branch
.fullPF1Bank8:
       LDA    #<PF1Bank8        ; 2             #7
.slopedPF1Bank8:
       STA    PF1LstNew         ; 3             store PF1 pointer
       JSR    GetPageFlag       ; 6             IN: X = wider of prev or new; OUT: A = 0
       SEC                      ; 2             set CF=1, A = 0
       ROL                      ; 2             roll bits left with CF, A = 1 ...ALWAYS!
       JSR    SetZoneVars_PF    ; 6             find and set bank pattern pointer
; Test in Stella Debugger if 11 page flags ever set:
;   breakif (*$8E&\11)==\11
; no
; Test in Stella Debugger if 00 page flags ever set:
;   breakif ((*$8E&\11)==\00)&&(*$C6==0)
; yes, *$C6==0 is to make sure game is running and not just 0 from a reset

.finishBanks:
       BIT    bankFlags         ; 3             INVERT_FLAG set?
       BPL    .skipSwapPF       ; 2             branch if not inverted banks
       LDA    PF1LstNew         ; 3              else swap PF1 and PF2 pointers
       LDX    PF2LstNew         ; 3               to execute the inverted PF draw of the islands
       STA    PF2LstNew         ; 3               (SetZoneVars_PF already swapped the page flags)
       STX    PF1LstNew         ; 3
.skipSwapPF:
;--------------------------------------

;--------------------------------------
; *** create new objects: ***
;--------------------------------------
       BIT    zoneLstNew        ; 3             PF_ROAD_FLAG set?
       BPL    .skipRoad         ; 2              no, skip
       LDA    #QUAD_SIZE        ; 2              yes, create road zone
       STA    State1LstNew      ; 3             quad size bridge
       LDY    #ID_BRIDGE        ; 2
       LDA    #63               ; 2             x-position (63, not 64, due to double and quad sprite-pos quirk)
       JMP    .endNewShape      ; 3
.skipRoad:
       LDY    #ID_FUEL          ; 2             Y = ID_FUEL
       LDA    block             ; 3
       CLC                      ; 2
       ADC    zone              ; 3
       CMP    #BLOCKS+ZONES     ; 2             house in first zone of first block of level
       BCS    .newHouse         ; 2
; create more enemies and less fuel in higher difficulty levels:
       LDA    #64               ; 2
       SBC    level             ; 3             1..48 (CF=0! causes A=A-level-1)
       ASL                      ; 2             A = 124..30
       CMP    randomHi          ; 3
       BCC    .newEnemy         ; 2             ~48%..88% -> more enemies, less fuel and houses
       BIT    randomLo          ; 3             AND-test on bit 6 (50/50)
       BVC    .newFuel          ; 2             ~24%.. 6% -> less fuel
; no enemy or fuel, create new house instead:
.newHouse:
       DEY                      ; 2             Y = ID_HOUSE
       LDX    newBankWidth      ; 3
       CPX    prevBankWidth     ; 3
       BCC    .newBankNarrower  ; 2
       LDX    prevBankWidth     ; 3
.newBankNarrower:               ;               X = smaller bank width
       LDA    #DOUBLE_SIZE      ; 2             house is double sized
       STA    State1LstNew      ; 3
       LDA    level             ; 3
       LSR                      ; 2
       BCC    .jagged           ; 2
; create random x-position for house in straight level:
       LDA    randomLo          ; 3             CF=1!
       AND    #$1F              ; 2
       ADC    #8                ; 2             +8 + 1 for CF
       CMP    #25               ; 2             random position fits in left bank?
       BCC    .randomizeDir     ; 2              yes, ok
       ADC    #92               ; 2              no, position house on right bank, +1 for CF
       BNE    .randomizeDir     ; 3

; position house in jagged level:
.jagged:
       LDA    HousePosTab,X     ; 4             x-pos lookup, indexed by smaller bank width
       BIT    bankFlags         ; 3             INVERT_FLAG set?
       BPL    .randomizeDir     ; 2              no, skip
       CPX    #0                ; 2             small bank width = 0?
       BEQ    .randomizeDir     ; 2              no, skip
       LDA    #71               ; 2             fixed position for house on island tip
       BNE    .randomizeDir     ; 3

; create new ship, helicopter or plane:
.newEnemy:
       LDA    #%111             ; 2
       LDX    level             ; 3
       CPX    #3                ; 2             enemy planes start at level three
       BCS    .withPlanes       ; 2
       LDA    #%001             ; 2             limit first levels to ship and helicopter
.withPlanes:
       AND    randomHi          ; 3             create random enemy object
       TAX                      ; 2
       LDY    EnemyIdTab,X      ; 4
.newFuel:
       CPY    #ID_SHIP          ; 2             if a ship was chosen, double the sprite width
       BNE    .notShip          ; 2
       LDA    #DOUBLE_SIZE      ; 2             doublesize
       STA    State1LstNew      ; 3
.notShip:
       LDA    newBankWidth      ; 3             really checking for last block of straight level
       CMP    prevBankWidth     ; 3             new bank width = previous bank width?
       BNE    .banksDiffWidth   ; 2              no, go find the wider one
       STA    maxBankWidths     ; 3              yes, store one as max
       LDA    level             ; 3
       LSR                      ; 2             straight or jagged level?
       BCC    .jagged2          ; 2

; position object in straight level (blocks 15..2):  CF = 1
       LDA    #106              ; 2 $FA06       max x-pos
       LDX    State1LstNew      ; 3             doublesize? (ship)
       BEQ    .notDoubleSize    ; 2              no, leave x-pos more right
       LDA    #97               ; 2              yes, move x-pos more left
.notDoubleSize:
       SBC    easyPadding       ; 3             decrease maximum position (-6) in first four levels,
                                ;                this avoids positioning near the right-hand bank
       STA    temp              ; 3             store maximum position
       LDA    randomLo          ; 3
       AND    #$3F              ; 2             00111111, 63
       ADC    #45               ; 2             +45 + 1 for CF
       ADC    easyPadding       ; 3             increase random position in first four levels (left bank)
       CMP    temp              ; 3             random position < maximum?
       BCC    .randomizeDir     ; 2              yes, ok
       LDA    temp              ; 3              no, position = maximum

.randomizeDir:
; make random direction for new shape:
       BIT    randomLo          ; 3
       BMI    .invertDirection  ; 2
       BPL    .endNewShape      ; 3

.banksDiffWidth:
       BCS    .newBankWider     ; 2
       LDA    prevBankWidth     ; 3
.newBankWider:
       STA    maxBankWidths     ; 3             store the wider bank width

; position object in jagged level (and first zone of last block of straight level):  CF = 0
; Enemies are never randomly in the middle of a jagged river like in the straights.
; They are always backed up against one bank or the other.
.jagged2:
; check, if there is enough space for new object:
       LDX    #13               ; 2 $FA2C          bank width limit for wide objects
       BIT    bankFlags         ; 3             INVERT_FLAG set?
       BPL    .notIsland        ; 2              no, skip
       LDX    #10               ; 2              yes, lower bank limit due to river split
.notIsland:
       CPX    maxBankWidths     ; 3             compare widest bank against limit
       BCS    .spaceOk          ; 2
       TYA                      ; 2             over limit for wide objects
       SBC    #ID_SHIP-1        ; 2             new enemy is a ship?
       BNE    .spaceOk          ; 2              no, skip
       STA    State1LstNew      ; 3              yes, change..
       DEY                      ; 2              ..ship into helicopter
.spaceOk:
       LDA    maxBankWidths     ; 3
       ASL                      ; 2             * 2
       ASL                      ; 2             * 2 = 4 sprite pixels/ PF pixel
       BEQ    .posSomewhere     ; 2             if in second zone of bank width 0 then skip
       BIT    bankFlags         ; 3             INVERT_FLAG set?
       BPL    .posSomewhere     ; 2              no, position somewhere
; position object for island:
       EOR    #$FF              ; 2
       ADC    #80+1             ; 2             CF = 0, sets CF=1            breakif {pc == $fa4c && c}
       BIT    randomLo          ; 3
       BPL    .setRightPadding  ; 2
       EOR    #$FF              ; 2
       ADC    #160              ; 2             +160 + 1 for CF              breakif {pc == $fa54 && !c}
       BNE    .setLeftPadding   ; 3

; position object for no island:
.posSomewhere:
       ADC    #16               ; 2             left border offset, CF = 0   breakif {pc == $fa58 && c}
       BIT    randomLo          ; 3
       BMI    .posOnRight       ; 2
.setLeftPadding:
       CLC                      ; 2
       ADC    #2                ; 2             CF = 0                       breakif {pc == $fa5f && c}
       ADC    easyPadding       ; 3             extra space (6) to left bank in first 4 levels
       BNE    .endNewShape      ; 3
.posOnRight:
       EOR    #$FF              ; 2             mirror x-pos left of 80 to right of 80
       ADC    #160+1            ; 2             CF = 0                       breakif {pc == $fa67 && c}
.setRightPadding:
       CPY    #ID_FUEL          ; 2             if obj == fuel {CF=1; ZF=1} else {CF=0; NF=1}
       SBC    #9                ; 2             x-pos -9 (or -10 if not fuel due to CF=0 quirk)
       SBC    easyPadding       ; 3             extra space (6) to right bank in first 4 levels
       LDX    State1LstNew      ; 3             double sized object? (ship, house)
       BEQ    .invertDirection  ; 2              no, skip
       SBC    #10               ; 2              yes, move 10 pixels left
.invertDirection:
       CPY    #ID_FUEL          ; 2             fuel?
       BEQ    .endNewShape      ; 2              yes, has constant direction
       PHA                      ; 3				push A to stack
       LDA    State1LstNew      ; 3
       ORA    #DIRECTION_FLAG   ; 2             set direction flag
       STA    State1LstNew      ; 3
       PLA                      ; 4             pull A from stack
.endNewShape:
       STY    Shape1IdLstNew    ; 3             save id of new object
       JSR    CalcPosX          ; 6
       STY    XPos1LstNew       ; 3             save coarse x-positioning value
       ORA    State1LstNew      ; 3
       STA    State1LstNew      ; 3             save fine x-positioning value
       JMP    .loopNext         ; 3

; ****************************** end of main loop ******************************


GameInit SUBROUTINE
; Input: x (= 22/38, number of initialized variables)
; initializes some variables for new game:
.initLoop:
       LDA    InitTab,X         ; 4 $FA8F
       STA    PF1Lst,X          ; 4
       DEX                      ; 2
       BPL    .initLoop         ; 2

; clear some variables for new game:
       LDA    #0                ; 2
       LDX    #30               ; 2
.loopClear:
       STA    speedX,X          ; 4
       DEX                      ; 2
       BPL    .loopClear        ; 2

       LDX    #MAX_ZONES-1      ; 2
       LDY    #PF1_PAGE_FLAG    ; 2
       LDA    level             ; 3
       LSR                      ; 2             straight level?
       BCC    .loopSet          ; 2              no, skip
       LDY    #PF1_PAGE_FLAG|PF_LTGREEN_FLAG; 2  yes, set brighter green in current level
.loopSet:
       STY    zoneLst,X         ; 4
       DEX                      ; 2
       BPL    .loopSet          ; 2
       RTS                      ; 6


