; flags for bankFlags:
INVERT_FLAG     = %10000000     ; banks inverted in block (for islands)
INVERT_NB_FLAG  = %01000000     ; banks will be inverted in Next Block (NB)
; Islands are created by inverting the direction the PF1 and PF2 banks are drawn.
; PF0 ensures a 4-pixel default bank is always present on the edges of the screen.
; (The left side hides the first 2 of the 4 pixels due to HMOVE.)
; Flag values (bits 7 + 6):
;   00 = normal   + next block normal   = 2..14 rand bank width
;   01 = normal   + next block inverted = 0 bank width (before island)
;   11 = inverted + next block inverted = 2..13 rand bank width (island)
;   10 = inverted + next block normal   = 0 bank width (after island)
; The second flag prevents flip-flopping from loop to loop before
; an island can actually be started.
; I suspect it would have been easier to understand, and to code, if
; the second flag here instead indicated whether or not the banks
; were just switched to island or back.  Or, more precisely, whether
; or not to allow bank switching--which is, after all, the only thing
; it is actually used for.

