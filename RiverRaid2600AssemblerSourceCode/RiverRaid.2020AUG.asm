; Level generation:
; The river is divided into levels which are generated by random. The random
; number generator can generate 57337 different levels. Each level is
; divided into 16 blocks. The last block is the bridge. For each other block a
; random Id is generated, which defines the shape of the river. The river is
; randomly generated with or without islands.
; Each block is 32 lines high and is divided into two zones. Those zones are
; neccessary for the bridge only, because it is smaller than a whole block.
;
; All objects are also randomly generated. There is one object in each block.
; First, the game randomly selects if a fuel tank, an enemy object (ship, plane
; or helicopter) or a house should be generated. Then, a starting x-position is
; defined and, finally, the direction (left/right) of the object is set.
; The ships and helicopters also start patrolling randomly.
;
; MJJ clarifications:
; * Each level is 16 blocks tall (32 sprite zones tall).
; * Each block is 64 lines tall and is divided into two sprite zones.
; * Each sprite zone is 32 lines tall and contains one non-player sprite
;   (in river or on land).
; * The bridge is one of those sprites and its zone is not otherwise special--
;   it is a 4x stretched sprite in the last zone of the last block.
; * A house is always in the first zone of the first block.
; * The river banks are defined per block but can look much smaller or
;   larger than a block due to the curious technique for bank sloping.
;   Negative sloping from the previous block occurs in about the middle of
;   the new block:
;   - Negative sloping always ends on line 31 (of 0..63).  -2?
;   - Positive sloping always begins on line 0.  -2?
; * Kernel notes corrected below regarding blocks and zones.
; MJJ Notes:
; * Internally, the levels are counted 1 to 48, then continuously repeating
;   47 and 48, as 48 is the max difficulty number. This does not mean the same
;   levels are repeated at that point, only the level variable is.
;
; Kernel:
; The main display is 160 lines tall. Below is the state display (score, fuel,
; lives and copyright).
; The kernel displays five or six of the sprite zones. When a zone leaves
; the display, it is replaced on the fly with a newly generated zone.
; It's basically a two line kernel, which is repeated twelve times. After that,
; there is code for eight more lines, where the zone is iterated and all new
; parameter are set. (12 * 2 + 8 = 32!)
; The parameters for each zone are:
; - a pointer to the current playfield pattern
; - a flag for a bright or dark green playfield
; - two pointers for the current object, the data is displayed interlaced,
;   this gives in a single line resolution here
; - a color pointer for the object
; - x-positioning values for the object
; - some flags for the object (size, reflection...)
; All collisons are checked for each displayed zone and only the hardware
; collision registers are used for that (no software calculations).

; Misc:
; - There are no score variables, the score is stored and changed directly in
;   the display pointers!  The same with lives.
; - The are no variables to store the x-positions of the objects, all
;   calculations are done directly with the position values.
;   (There aren't any BCD calculations in this code!)
; - All variables for the players are swapped, when the players change.
; - The game speeds aren't adjusted for PAL, the PAL game run's about 16% slower.
;   (This seems to be true for most PAL conversions.)
; - ...

