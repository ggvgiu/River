SetZoneVars_PF SUBROUTINE
; INPUT:  A = %00 or %01 (not possible: %11, and especially %10)
;         X = bank width
; RETURN: Y = %00 or %01  (input A)   trash
;         zoneLstNew    = zoneLstNew plus new PFx Page Flags
;         PF2LstNew = A = ptr to bank PF pattern
; Sets zone list variables for PF page flags and PF pattern pointers.
       BIT    bankFlags         ; 3             INVERT_FLAG set?
       BPL    .normalBanks2     ; 2             branch if not inverted banks
       TAY                      ; 2              else copy A to Y
       LDA    PageFlagInverter,Y; 4               A = 0 -> 0, A = %01 -> %10, (not used: %11 -> %11)
.normalBanks2:
       ORA    zoneLstNew        ; 3             add page flags to zoneLst
