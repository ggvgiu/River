       ORG $F000

START:
       SEI                      ; 2
       CLD                      ; 2
       LDX    #0                ; 2
Reset:
       LDA    #0                ; 2
.loopClear:
       STA    $00,X             ; 4
       TXS                      ; 2
       INX                      ; 2
       BNE    .loopClear        ; 2
       JSR    SetScorePtrs      ; 6
       LDA    #>Zero            ; 2
       LDX    #12-1             ; 2
       JSR    SetScorePtr1      ; 6             set high-pointers to $FB
       LDX    #colorPtr+1-PF1Lst; 2             #38, counter to fill 39 bytes from PF1Lst to colorPtr(hi)...
       JSR    GameInit          ; 6              when this is called
       LDA    random8           ; 3             booting first time?
       BNE    MainLoop          ; 2              no, branch to main
       INC    random8           ; 5              yes, set boot values: random = 1
       STA    livesPtr          ; 3               = 0, select mode  (it was at 88, $58, which would start new game)
       LDA    #<One             ; 2
       STA    scorePtr1+10      ; 3               = 8  (it was at 0)


MainLoop:
       LDX    #4                ; 2             offset ball for SetPosX (HMP0 address + 4 = HMBL)
       LDA    fuelHi            ; 3
       LSR                      ; 2
       LSR                      ; 2
       LSR                      ; 2
       CLC                      ; 2
       ADC    #69               ; 2
       JSR    SetPosX           ; 6             position ball for fuel display


; *** prepare everything for the main kernel: ***
; set all color registers (and NUSIZ1 = 0)
       INX                      ; 2             x = 5!
.loopSetColors:
       LDA    ColorTab,X        ; 4
  IF SCREENSAVER
       EOR    SS_XOR            ; 3
       AND    SS_Mask           ; 3
  ELSE
       FILL_NOP 4
  ENDIF
       STA    PFcolor,X         ; 4
       STA    NUSIZ1,X          ; 4
       DEX                      ; 2
       BPL    .loopSetColors    ; 2
       TAY                      ; 2             y = 0!
       LDA    scorePtr1+10      ; 3
       CMP    #<Two             ; 2
       BEQ    .skipTwo          ; 2
       LDA    SWCHB             ; 4
       LSR                      ; 2             reset pressed?
       BCC    .skipTwo          ; 2              yes, skip player 2
       LDA    player            ; 3             current player = 2?
       BEQ    .skipTwo          ; 2              no, skip
       STY    playerColor       ; 3              yes, set..
       STY    COLUP0            ; 3              ..and player 2 color = 0
.skipTwo:

; flicker background when bridge explodes:
       LDA    bridgeExplode     ; 3
       BEQ    .skipExplosion    ; 2
       DEC    bridgeExplode     ; 5
       LSR                      ; 2
       BCC    .skipExplosion    ; 2
       LDA    #DARK_RED         ; 2             flicker background red
  IF SCREENSAVER
       AND    SS_Mask           ; 3
  ELSE
       FILL_NOP 2
  ENDIF
       STA    COLUBK            ; 3
.skipExplosion:

       INX                      ; 2             x = 0! (player jet)
       STX    temp              ; 3
       STX    NUSIZ0            ; 3
       LDY    playerX           ; 3             y = player's x-pos
       LDA    reflect0          ; 3
       STA    REFP0             ; 3
       BEQ    .noReflect        ; 2
       INY                      ; 2             adjust x-pos +1 if reflected (due to width 7)
.noReflect:
       TYA                      ; 2             a = y
       JSR    SetPosX           ; 6             x-position player jet
       INX                      ; 2             x = 1 (enemy object)
       STX    CTRLPF            ; 3             reflect playfield

       STX    VDELP1            ; 3             enable vertical delay for player 1

; set size, reflect and position for top enemy object;
       LDY    XPos1Lst +MAX_ZONES-1; 3
       LDA    State1Lst+MAX_ZONES-1; 3
       STA    NUSIZ1            ; 3
       STA    REFP1             ; 3
       JSR    SetPosX2          ; 6             x-position top enemy object

; x-position missile:
       INX                      ; 2             x = 2 (player missile)
       LDA    missileX          ; 3             a = missile's x-pos
       JSR    SetPosX           ; 6             x-position missile

       JSR    DoHMove           ; 6             do HMOVE
       STY    PF0               ; 3             y=$ff, sets defualt bank of 4 bits on each side (PF0 = PF bits 0-3)

; clear collision variables:
       STY    hitEnemyIdx       ; 3
       STY    PFCrashFlag       ; 3
       STY    missileFlag       ; 3
       STY    collidedEnemy     ; 3

; set variables for top zone:
       LDX    #MAX_ZONES-1      ; 2
       JSR    SetPFxPtr         ; 6
       LDA    zoneOffset        ; 3
       CMP    #3                ; 2             top zone just started?
       BCS    .skipDex          ; 2              no, skip
       DEX                      ; 2              yes, start at zone 4
.skipDex:
       STX    zoneNum           ; 3  $F0A8
       LDY    Shape1IdLst,X     ; 4
       LDX    shapePtr1aTab,Y   ; 4
       STX    shapePtr1a        ; 3
       LDX    shapePtr1bTab,Y   ; 4
       STX    shapePtr1b        ; 3
       LDX    ColorPtrTab,Y     ; 4
       STX    colorPtr          ; 3
       STA    CXCLR             ; 3             clear all collison registers
       STA    HMCLR             ; 3
; calculate offset into first zone:
       TAX                      ; 2
       SEC                      ; 2
       SBC    #1                ; 2
       AND    #$1F              ; 2             31, 00011111
       STA    zoneLine          ; 3
       LSR    zoneLine          ; 5             0..15
       CMP    #26               ; 2
       BCC    lowOffset         ; 2
       SBC    #22               ; 2
       BNE    endOffset         ; 2

lowOffset:
       CMP    #4                ; 2
       BCC    endOffset         ; 2
       AND    #%01              ; 2
       ORA    #%10              ; 2
endOffset:

; set entrypoint into kernel:
       TAY                      ; 2
       LDA    JmpHiTab,Y        ; 4
       PHA                      ; 3
       LDA    JmpLoTab,Y        ; 4
       PHA                      ; 3

; prepare graphics for first line of kernel:
       TXA                      ; 2
       LSR                      ; 2
       TAY                      ; 2
       LDA    (shapePtr1a),Y    ; 5
       BCC    .evenLine         ; 2             even zoneOffset!
       LDA    (shapePtr1b),Y    ; 5
.evenLine:
       CPX    #26               ; 2             zoneOffset >= 26?
       BCS    .noShape          ; 2              yes, skip enemy shape
       CPX    #3                ; 2             zoneOffset < 3?
       BCC    .noShape          ; 2              yes, skip enemy shape
       STA    GRP1              ; 3              no, display enemy shape in first row
       LDA    #0                ; 2
       STA    GRP0              ; 3             VDELP1!
.noShape:
       LDA    (PF1Ptr),Y        ; 5
       STA    PF1               ; 3             draw to playfield line buffer, bits 4-11
       LDA    (PF2Ptr),Y        ; 5
       STA    PF2               ; 3             draw to playfield line buffer, bits 19-12
       LDA    (colorPtr),Y      ; 5
  IF SCREENSAVER
       EOR    SS_XOR            ; 3
       AND    SS_Mask           ; 3
  ELSE
       FILL_NOP 4
  ENDIF
       STA    COLUP1            ; 3
       LDX    zoneNum           ; 3
       LDA    zoneLst,X         ; 4
       STA    roadZone          ; 3             save road-state
       AND    #PF_LTGREEN_FLAG  ; 2
       ORA    #GREEN            ; 2
  IF SCREENSAVER
       EOR    SS_XOR            ; 3
       AND    SS_Mask           ; 3
  ELSE
       FILL_NOP 4
  ENDIF
       STA    PFcolor           ; 3
       BIT    zoneLstNew        ; 3             road in first zone?
       BPL    .noRoad           ; 2              no, use green color
       CPY    #ROAD_HEIGHT      ; 2             offset inside road?
       BCS    .noRoad           ; 2              no, use green color
       LDA    RoadColorTab,Y    ; 4              yes, use road colors
  IF SCREENSAVER
       EOR    SS_XOR            ; 3
       AND    SS_Mask           ; 3
  ELSE
       FILL_NOP 4
  ENDIF
.noRoad:
       STA    COLUPF            ; 3
       LDY    #MAIN_LINES       ; 2
       STY    lineNum           ; 3
.waitTim:
       LDA    INTIM             ; 4             read timer
       BNE    .waitTim          ; 2             loop if timer not zero yet
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line
       STA    HMOVE             ; 3             must follow WSYNC if horizontal motion desired
       STA    VBLANK            ; 3             turn off the beam during vertical timing
       RTS                      ; 6             jump into kernel!


; *** main display kernel: ***
DisplayKernel SUBROUTINE


; first some external code to save cycles in the kernel:
JmpPoint2:                      ;12
       INC    lineNum           ; 5 $F13A
       LDY    zoneLine          ; 3
       BPL    enterKernel2      ; 3

.skipJet0:
       LDX    zero2             ; 3             load 0 with exactly 3 cylces
       BEQ    .contJet0         ; 3

.noRoad:
       LDA    PFcolor           ; 3
       JMP    .contPFColor      ; 3

.doJet0a:
       LDA    (shapePtr0),Y     ; 5
       TAX                      ; 2
       LDA    #$00              ; 2
.loopKernel1:                   ;   @19
       BEQ    .contJet0a        ; 2             this jump is taken when comming from .doJet0a
       BNE    .contKernel1      ; 3             this jump is taken when comming from .loopkernel1

  IF SCREENSAVER = 0
       FILL_NOP 1
  ENDIF

JmpPoint3:                      ;12
       JSR    Wait12            ;12
.contKernel1:
       NOP                      ; 2 @26



; ********************* here starts the main kernel loop: **********************

;--------------------------------------
; even line:
; - ...
; - draw player jet
; - load new P1 shape
.loopKernel:                    ;
       CPY    #JET_Y            ; 2 $F156       draw player jet?
       BCS    .skipJet0         ; 2              no, skip
       LDA    (shapePtr0),Y     ; 5              yes, load data..
       TAX                      ; 2              ..into x
.contJet0:
       LDY    zoneLine          ; 3
       BIT    roadZone          ; 3             road displayed?
       BPL    .noRoad           ; 2              no, normal PF color
       LDA    RoadColorTab,Y    ; 4              yes, load road colors
  IF SCREENSAVER
       EOR    SS_XOR            ; 3
.contPFColor:
       AND    SS_Mask           ; 3
  ELSE
       FILL_NOP 2
.contPFColor:
       FILL_NOP 1
  ENDIF
       STA.w  temp              ; 4             MJJ: !!!!!! .w???
       LDA    (shapePtr1b),Y    ; 5
       STA    GRP1              ; 3             time doesn't matter (VDELP1!)
       LDA    (PF1Ptr),Y        ; 5
       STA    PF1               ; 3 @75         draw to playfield line buffer, bits 4-11
;--------------------------------------
; new line starts here!
; odd line:
; - set PF color
; - set P1 color
; - change PF
       STA    HMOVE             ; 3 $F175       must follow WSYNC if horizontal motion desired
       STX    GRP0              ; 3 @2          this also updates GRP1
       LDA    temp              ; 3
       STA    COLUPF            ; 3 @8
       LDA    (colorPtr),Y      ; 5
  IF SCREENSAVER
       EOR    SS_XOR            ; 3
       AND    SS_Mask           ; 3
  ELSE
       FILL_NOP 4
  ENDIF
       STA    COLUP1            ; 3 @22
       LDA    (PF2Ptr),Y        ; 5
       STA    PF2               ; 3 @30         draw to playfield line buffer, bits 19-12
enterKernel2:
       LDA    (shapePtr1a),Y    ; 5
       STA    GRP1              ; 3             time doesn't matter (VDELP1!)
       LDY    lineNum           ; 3
       DEY                      ; 2
       BEQ    .exitKernel2      ; 2
       CPY    #JET_Y            ; 2
       BCC    .doJet0a          ; 2
       TYA                      ; 2
       SBC    missileY          ; 3
       AND    #$F8              ; 2
       BNE    .skipEnable0      ; 2
       LDA    #ENABLE           ; 2
.skipEnable0:
       LDX    #$00              ; 2
.contJet0a:
       DEY                      ; 2
       STY    lineNum           ; 3
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line
;--------------------------------------
; even line:
; - en-/disable missile
; - update P0 and P1 graphics
; - decrease zone-line
; - ...
       STA    HMOVE             ; 3 $F1A6       must follow WSYNC if horizontal motion desired
       STA    ENAM0             ; 3
       STX    GRP0              ; 3 @6          this also updates GRP1
       BEQ    .exitKernel2      ; 2
       DEC    zoneLine          ; 5
       BNE    .loopKernel1      ; 2


;*** start of next zone (requires eight extra kernel lines): ***
;--------------------------------------
; new zone, line 1
; - dec zone-number
; - set new  road-state
; - get new PF color
;  - set new shape-pointer 1a
;--------------------------------------
       DEC    zoneNum           ; 5 $F1B2
JmpPoint1:
       LDX    zoneNum           ; 3
       BMI    LF202             ; 2
       LDA    zoneLst,X         ; 4             save road-state
       STA    roadZone          ; 3
       AND    #PF_LTGREEN_FLAG  ; 2             bright or dark..
       ORA    #GREEN            ; 2             ..green
  IF SCREENSAVER
       EOR    SS_XOR            ; 3
       AND    SS_Mask           ; 3
  ELSE
       FILL_NOP 4
  ENDIF
       STA    PFcolor           ; 3
       LDA    Shape1IdLst,X     ; 4             set
       TAX                      ; 2              shape-pointer
       LDA    shapePtr1aTab,X   ; 4              for the
       STA    shapePtr1a        ; 3              next enemy
LF1CE:
       LDA    #$00              ; 2
       STA    GRP1              ; 3
       CPY    #JET_Y            ; 2
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line

;--------------------------------------
; new zone, line 2
; x = shape-id
;  - set jet
;  - set PF
;  - set new shape-pointer 1b
;  - set new color-pointer
;--------------------------------------
       STA    HMOVE             ; 3 $F1D6       must follow WSYNC if horizontal motion desired
       BCS    .skipJet1         ; 2
       LDA    (shapePtr0),Y     ; 5
.skipJet1:
       STA    GRP0              ; 3
       LDY    #0                ; 2             display last line of playfield pattern
       LDA    (PF1Ptr),Y        ; 5
       STA    PF1               ; 3             draw to playfield line buffer, bits 4-11
       LDA    (PF2Ptr),Y        ; 5
       STA    PF2               ; 3             draw to playfield line buffer, bits 19-12
       LDY    lineNum           ; 3
       DEY                      ; 2
.exitKernel2:
       BEQ    .exitKernel1      ; 2
       LDA    shapePtr1bTab,X   ; 4
       STA    shapePtr1b        ; 3
       LDA    ColorPtrTab,X     ; 4
       STA    colorPtr          ; 3
JmpPoint0:
       CPY    #JET_Y            ; 2
       BCS    .skipJet2         ; 2
       LDA    (shapePtr0),Y     ; 5
       TAX                      ; 2
       LDA    #DISABLE          ; 2
       BEQ    .contJet2         ; 3

LF202: INX                      ; 2
       BEQ    LF1CE             ; 2
JmpPoint9:
       NOP                      ; 2
       SEC                      ; 2
       BCS    .enterKernel9     ; 3

.skipJet2:
       TYA                      ; 2
       SBC    missileY          ; 3
       AND    #$F8              ; 2
       BNE    .skipEnable1      ; 2
       LDA    #ENABLE           ; 2
.skipEnable1:
       LDX    #$00              ; 2
.contJet2:
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line

;--------------------------------------
; new zone, line 3
; - en-/disabvle missile
; - set jet
; - set new PF pointers
;--------------------------------------
       STA    HMOVE             ; 3 $F216       must follow WSYNC if horizontal motion desired
       STA    ENAM0             ; 3
       STX    GRP0              ; 3
       DEY                      ; 2
       STY    lineNum           ; 3
.exitKernel1:
       BEQ    .exitKernel       ; 2
       LDX    zoneNum           ; 3
.enterKernel9:
       JSR    SetPFxPtr         ;50
       LDA    PFcolor           ; 3
       CPY    #JET_Y            ; 2
       NOP                      ; 2 @76

;--------------------------------------
; new zone, line 4
; - set new PF color
; - set PF
; - load fine movement
;--------------------------------------
       STA    HMOVE             ; 3 $F22B       must follow WSYNC if horizontal motion desired
       STA    COLUPF            ; 3
       BCS    .skipJet3         ; 2
       LDA    (shapePtr0),Y     ; 5
       STA    GRP0              ; 3
.skipJet3:
       LDY    #BLOCKS        -1 ; 2
       LDA    (PF1Ptr),Y        ; 5
       STA    PF1               ; 3             draw to playfield line buffer, bits 4-11
       LDA    (PF2Ptr),Y        ; 5
       STA    PF2               ; 3             draw to playfield line buffer, bits 19-12
       DEC    lineNum           ; 5
       BEQ    .exitKernel       ; 2
JmpPoint8:
       LDA    State1Lst,X       ; 4             put fine x-pos
       STA    temp              ; 3              into temp
       LDY    lineNum           ; 3
       CPY    #JET_Y            ; 2
       BCC    .skipJet4         ; 2
       TYA                      ; 2
       SBC    missileY          ; 3
       AND    #$F8              ; 2
       BNE    .skipEnable2      ; 2
       LDA    #ENABLE           ; 2
.skipEnable2:
       LDY    #0                ; 2
.contJet4:
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line

;--------------------------------------
; new zone, line 5
; - en-/disable missile
; - set jet
; - position new shape
;--------------------------------------
       STA    HMOVE             ; 3 $F25A       must follow WSYNC if horizontal motion desired
       STA    ENAM0             ; 3
       STY    GRP0              ; 3
; position player 1:
       LDA    XPos1Lst,X        ; 4             load coarse move-value
       BEQ    .posVeryLeft      ; 2
       TAX                      ; 2
       CPX    #7                ; 2
       BCS    .posRight         ; 2
.waitLeft:
       DEX                      ; 2
       BNE    .waitLeft         ; 2
       STA    RESP1             ; 3
.contLeft:
       DEC    lineNum           ; 5
       LDY    lineNum           ; 3
       BNE    .contPos          ; 2
.exitKernel:
       JMP    DisplayState      ; 3             exit the kernel

.posVeryLeft:
       NOP                      ; 2
       NOP                      ; 2
       LDA    #$60              ; 2
       STA    RESP1             ; 3
       STA    HMP1              ; 3
       BNE    .contLeft         ; 2

.skipJet4:
       LDA    (shapePtr0),Y     ; 5
       TAY                      ; 2
       LDA    #$00              ; 2
       BEQ    .contJet4         ; 2

.posRight:
       SBC    #4                ; 2
       TAX                      ; 2
       DEC    lineNum           ; 5
       LDY    lineNum           ; 3
       BEQ    .exitKernel       ; 2
.waitRight:
       DEX                      ; 2
       BPL    .waitRight        ; 2
       STA    RESP1             ; 3
JmpPoint7:
.contPos:
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line

;--------------------------------------
; new zone, line 6
;--------------------------------------
       STA    HMOVE             ; 3 $F298       must follow WSYNC if horizontal motion desired
       CPY    #JET_Y            ; 2
       BCS    .skipJet5         ; 2
       LDA    (shapePtr0),Y     ; 5
       STA    GRP0              ; 3
.skipJet5:
       LDY    #BLOCKS        -2 ; 2
       LDA    (PF1Ptr),Y        ; 5
       STA    PF1               ; 3             draw to playfield line buffer, bits 4-11
       LDA    (PF2Ptr),Y        ; 5
       STA    PF2               ; 3             draw to playfield line buffer, bits 19-12
       LDY    lineNum           ; 3
       DEY                      ; 2
       BEQ    .exitKernel       ; 2
       LDX    zoneNum           ; 3
       LDA    temp              ; 3             load fine x-pos of enemy
       STA    HMP1              ; 3              and set it
JmpPoint6:
       LDA    #[ZONE_LINES-8]/2 ; 2
       STA    zoneLine          ; 3
       TYA                      ; 2
       SEC                      ; 2
       SBC    missileY          ; 3
       AND    #$F8              ; 2
       BNE    .skipEnable3      ; 2
       LDA    #ENABLE           ; 2
.skipEnable3:
       CPY    #JET_Y            ; 2
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line

;--------------------------------------
; new zone, line 7
;--------------------------------------
       STA    HMOVE             ; 3 $F2C9       must follow WSYNC if horizontal motion desired
       STA    ENAM0             ; 3
       BCS    .skipJet6         ; 2
       LDA    (shapePtr0),Y     ; 5
       STA    GRP0              ; 3
.skipJet6:
       LDA    State1Lst,X       ; 4
       STA    NUSIZ1            ; 3
       STA    REFP1             ; 3
       DEY                      ; 2
       STY    lineNum           ; 3
       BEQ    DisplayState      ; 2
       STA    HMCLR             ; 3

; check collisions:
; (the collsion check between jet or missile and playfield aren't
;  really neccessary for each zone, but the collison registers
;  are cleared after each zone)
       INX                      ; 2
       BIT    CXM0P-$30         ; 3             player missile hit enemy?
       BPL    .notHit           ; 2
       STX    hitEnemyIdx       ; 3             save zone number
.notHit:
  IF TRAINER
       BIT    zero1
  ELSE
       BIT    CXP0FB-$30        ; 3             jet hit PF?
  ENDIF
       BPL    .noPFCrash        ; 2
       STX    PFCrashFlag       ; 3
.noPFCrash:
  IF TRAINER
       BIT    zero1
  ELSE
       BIT    CXM0FB-$30        ; 3             player missile hit PF?
  ENDIF
       BPL    .notHitPF         ; 2
       STX    missileFlag       ; 3
.notHitPF:
  IF TRAINER
       BIT    zero1
  ELSE
       BIT    CXPPMM-$30        ; 3             jet crashed into enemy?
  ENDIF
       BPL    .noCrash          ; 2
       STX    collidedEnemy     ; 3             save zone number
.noCrash:

.enterKernel5:
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line

;--------------------------------------
; new zone, line 8
;--------------------------------------
       STA    HMOVE             ; 3 $F2FB       must follow WSYNC if horizontal motion desired
       CPY    #JET_Y            ; 2
       BCS    .skipJet7         ; 2
       LDA    (shapePtr0),Y     ; 5
       STA    GRP0              ; 3
.skipJet7:
       LDY    #BLOCKS        -3 ; 2
       LDA    (PF1Ptr),Y        ; 5
       STA    PF1               ; 3             draw to playfield line buffer, bits 4-11
       LDA    (PF2Ptr),Y        ; 5
       STA    PF2               ; 3             draw to playfield line buffer, bits 19-12
       LDY    lineNum           ; 3
       DEY                      ; 2
       BEQ    DisplayState      ; 2
       BIT    CXP1FB-$30        ; 3             enemy hit PF?
       BPL    .notEnemyPF       ; 2              no, skip
       LDA    zoneLst,X         ; 4
       ORA    #PF_COLLIDE_FLAG  ; 2              yes, set collision flag
       STA    zoneLst,X         ; 4
.notEnemyPF:
       STA    CXCLR             ; 3             clear all collison registers

.enterKernel4:
       TYA                      ; 2
       SEC                      ; 2
       SBC    missileY          ; 3
       AND    #$F8              ; 2
       BNE    .skipEnable4      ; 2
       LDA    #ENABLE           ; 2
.skipEnable4:
       CPY    #JET_Y            ; 2
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line

;--------------------------------------
; new zone, line 9 (= begin of even line)
;--------------------------------------
       STA    HMOVE             ; 3 $F32E       must follow WSYNC if horizontal motion desired
       STA    ENAM0             ; 3
       BCS    .skipJet8         ; 2
       LDA    (shapePtr0),Y     ; 5
       STA    GRP0              ; 3
.contJet8:
       DEY                      ; 2
       STY    lineNum           ; 3
       BEQ    DisplayState      ; 2             exit the kernel
       JMP    .loopKernel       ; 3 @26

JmpPoint5:
       LDA    #[ZONE_LINES-8]/2 ; 2
       STA    zoneLine          ; 3
       BNE    .enterKernel5     ; 3

JmpPoint4:
       LDA    #[ZONE_LINES-8]/2 ; 2             12
       STA    zoneLine          ; 3
       BNE    .enterKernel4     ; 3

.skipJet8:                      ;               waste some time
       NOP                      ; 2
       NOP                      ; 2
       BCS    .contJet8         ; 3

;--------------------------------------
DisplayState SUBROUTINE
;--------------------------------------
; finish display kernel:
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line
       STA    HMOVE             ; 3 $5352       must follow WSYNC if horizontal motion desired
       LDY    #$00              ; 2
       STY    GRP1              ; 3
       STY    GRP0              ; 3
       LDA    zero1             ; 3             waste one extra cylce (but also wastes a variable!)
       STA    COLUBK            ; 3             black line before gray state background
       STY    PF0               ; 3             no playfield bits (next three lines)
       STY    PF1               ; 3
       STY    PF2               ; 3
       STY    REFP0             ; 3
       STY    REFP1             ; 3
       STY    reflect0          ; 3
; prepare state display:
       LDA    #$11              ; 2             reflect PF, 2 pixel ball width, also for HMP0!
       STA    RESP0             ; 3
       STA    RESP1             ; 3
       STA    CTRLPF            ; 3
       STA    HMP0              ; 3
       LDA    #$20              ; 2
       STA    HMP1              ; 3
       LDA    playerColor       ; 3
       JSR    SetColPx          ; 6
       LDA    stateBKColor      ; 3             state display background set to gray
       STA    COLUBK            ; 3
       LDA    #THREE_COPIES     ; 2
       STA    NUSIZ0            ; 3
       STA    NUSIZ1            ; 3
       LDA    statePFColor      ; 3
       STA    COLUPF            ; 3
       LDY    #$07              ; 2
       STY    VDELP0            ; 3
       STY    lineNum           ; 3
       STA    HMCLR             ; 3
; display score:
.loopScore:
       LDA    (scorePtr1+8),Y   ; 5
       TAX                      ; 2
       LDA    (scorePtr1+10),Y  ; 5
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line
       STA    HMOVE             ; 3             must follow WSYNC if horizontal motion desired
       STY    temp2             ; 3
       STA    temp              ; 3
       LDA    (scorePtr1),Y     ; 5
       STA    GRP0              ; 3
       LDA    (scorePtr1+2),Y   ; 5
       STA    GRP1              ; 3
       LDA    (scorePtr1+4),Y   ; 5
       STA    GRP0              ; 3
       LDA    (scorePtr1+6),Y   ; 5
       LDY    temp              ; 3
       STA    GRP1              ; 3
       STX    GRP0              ; 3
       STY    GRP1              ; 3
       STA    GRP0              ; 3
       LDY    temp2             ; 3
       DEY                      ; 2
       BPL    .loopScore        ; 2

       LDA    zero1             ; 3             a = 0 (BLACK)
       JSR    FinishDigits      ; 6             y = 14
; display fuel:
.loopFuel:
       STY    temp2             ; 3             line counter
       LDA    FuelTab4,Y        ; 4
       LDX    FuelTab3,Y        ; 4
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line
       STA    HMOVE             ; 3             must follow WSYNC if horizontal motion desired
       STA    temp              ; 3
       NOP                      ; 2
       LDA    #$00              ; 2
       STA    GRP0              ; 3
       LDA    ENABLTab,Y        ; 4
       STA    ENABL             ; 3
       LDA    FuelTab0,Y        ; 4
       STA    GRP1              ; 3
       LDA    FuelTab1,Y        ; 4
       STA    GRP0              ; 3
       LDA    FuelTab2,Y        ; 4
       LDY    temp              ; 3
       STA    GRP1              ; 3
       STX    GRP0              ; 3
       STY    GRP1              ; 3
       STA    GRP0              ; 3
       LDY    temp2             ; 3
       DEY                      ; 2
       BPL    .loopFuel         ; 2

       LDA    playerColor       ; 3
       JSR    FinishDigits      ; 6
       INY                      ; 2             y=15
       CLC                      ; 2
       LDX    gameMode          ; 3
       INX                      ; 2
       BNE    .noGame           ; 2
       LDA    #<Space           ; 2
       STA    livesPtr          ; 3

; animate copyright message:
       LDA    frameCnt          ; 3
       LSR                      ; 2
       LSR                      ; 2
       LSR                      ; 2
       CMP    #20               ; 2
       BCS    .ok               ; 2
       CMP    #12               ; 2
.noGame:
       LDY    #7                ; 2
       BCC    .ok               ; 2
       SBC    #4                ; 2
       TAY                      ; 2
.ok:
       STY    temp3             ; 3             copyright scroll offset
; display lives and copyright:
.loopCopyright:
       LDY    temp3             ; 3
       LDA    Copyright5,Y      ; 4
       STA    temp              ; 3
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line
       STA    HMOVE             ; 3             must follow WSYNC if horizontal motion desired
       LDX    Copyright4,Y      ; 4
       LDA    (livesPtr),Y      ; 5
       STA    GRP0              ; 3
       DEC    temp3             ; 5
       LDA    Copyright1,Y      ; 4
       STA    GRP1              ; 3
       LDA    Copyright2,Y      ; 4
       STA    GRP0              ; 3
       LDA    Copyright3,Y      ; 4
       LDY    temp              ; 3
       STA    GRP1              ; 3
       STX    GRP0              ; 3
       STY    GRP1              ; 3
       STA    GRP0              ; 3
       DEC    lineNum           ; 5
       BPL    .loopCopyright    ; 2

       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line
       STA    HMOVE             ; 3             must follow WSYNC if horizontal motion desired
       LDX    #$00              ; 2
       STX    VDELP0            ; 3
       STX    GRP1              ; 3
       STX    GRP0              ; 3
       LDA    zoneOffset        ; 3
       CMP    #ZONE_LINES-6     ; 2
       BCC    .skipInx          ; 2
       INX                      ; 2
.skipInx:

; check collisions for the last displayed zone:
       BIT    CXM0P-$30         ; 3             player missile hit enemy?
       BPL    .notHit2          ; 2
       STX    hitEnemyIdx       ; 3             save zone number
.notHit2:
  IF TRAINER
       BIT    zero1
  ELSE
       BIT    CXP0FB-$30        ; 3             jet hit PF?
  ENDIF
       BPL    .noPFCrash2       ; 2
       STX    PFCrashFlag       ; 3
.noPFCrash2:
       BIT    CXM0FB-$30        ; 3             player missile hit PF?
       BPL    .notHitPF2        ; 2
       STX    missileFlag       ; 3
.notHitPF2:

  IF NTSC
       LDA    #29               ; 2
  ELSE
       LDA    #58               ; 2
  ENDIF
       LDY    #%10000010        ; 2
       STA    WSYNC             ; 3             wait for sync; wait for TIA to finish line
       STA    TIM64T            ; 4
       STY    VBLANK            ; 3

       BIT    CXP1FB-$30        ; 3             enemy hit PF?
       BPL    .notEnemyPF2      ; 2
       LDA    zoneLst,X         ; 4
       ORA    #PF_COLLIDE_FLAG  ; 2
       STA    zoneLst,X         ; 4
.notEnemyPF2:
  IF TRAINER
       LDA    zero1
  ELSE
       BIT    CXPPMM-$30        ; 3             jet crashed into enemy?
  ENDIF
       BPL    .noCrash2         ; 2
       STX    collidedEnemy     ; 3             save zone number
.noCrash2:

; *** update framecounter, check for screensaver: ***
       DEC    frameCnt          ; 5
       BNE    .skipSS_Delay     ; 2
       LDX    gameMode          ; 3
       INX                      ; 2
       BNE    .skipInit         ; 2
       JSR    SwapPlayers       ; 6
.skipInit:
  IF SCREENSAVER
       INC    SS_Delay          ; 5
       BNE    .skipSS_Delay     ; 2
       SEC                      ; 2
       ROR    SS_Delay          ; 5
  ELSE
       FILL_NOP 4
  ENDIF
.skipSS_Delay:
  IF SCREENSAVER
       LDY    #$FF              ; 2
       LDA    SWCHB             ; 4
       AND    #BW_MASK          ; 2             black and white?
       BNE    .colorMode        ; 2              no, color mode
       LDY    #$0F              ; 2              yes, mask out high nibble
.colorMode:
       TYA                      ; 2
       LDY    #$00              ; 2
       BIT    SS_Delay          ; 3
       BPL    .noScreenSaver    ; 2
       AND    #$F7              ; 2
       LDY    SS_Delay          ; 3
.noScreenSaver:
       STY    SS_XOR            ; 3
       ASL    SS_XOR            ; 5
       STA    SS_Mask           ; 3
  ELSE
       FILL_NOP 28
  ENDIF

; *** randomly start movement of enemies: ***
       LDA    random8           ; 3
       ASL                      ; 2
       ASL                      ; 2
       ASL                      ; 2
       EOR    random8           ; 3
       ASL                      ; 2
       ROL    random8           ; 5
       LDA    frameCnt          ; 3
       AND    #$0F              ; 2             every 16th frame
       BNE    .skipStartMove    ; 2
       LDA    random8           ; 3
       AND    #$07              ; 2
       CMP    #5                ; 2             start one of the first five enemies
       BCC    .inBound          ; 2
       SBC    #5                ; 2             doublish chances for the first three enemies (68.75:31.25)
.inBound:
       TAX                      ; 2
       LDA    zoneLst,X         ; 4             start
       ORA    #ENEMY_MOVE_FLAG  ; 2              movement
       STA    zoneLst,X         ; 4              of enemy
.skipStartMove:

;*** animate and move the enemy objects: ***
       LDX    #MAX_ZONES-1      ; 2
.loopEnemies:
; animate some enemies:
       LDY    Shape1IdLst,X     ; 4
       CPY    #ID_SHIP          ; 2             don't animate ship, bridge, house and fuel
       BCS    .skipAnimate      ; 2
       LDA    #$01              ; 2             every 2nd frame
       CPY    #ID_PLANE         ; 2             fast animate plane (not done) and helicopter
       BCS    .fastAnimation    ; 2
       LDA    #$0F              ; 2             slow animate explosions (every 16th frame)
.fastAnimation:
       AND    frameCnt          ; 3
       BNE    .skipAnimate      ; 2
       LDA    AnimateIdTab,Y    ; 4
       STA    Shape1IdLst,X     ; 4
       TAY                      ; 2
.skipAnimate:

; check for move and direction change:
       LDA    gameMode          ; 3
       BNE    .skipMoveEnemy    ; 2
       LDA    level             ; 3
       LSR                      ; 2             first level?
       BEQ    .skipMoveEnemy    ; 2              yes, don't move
       CPY    #ID_PLANE         ; 2             move plane in same direction every frame
       BEQ    .xMoveEnemy       ; 2
       BCC    .skipMoveEnemy    ; 2
       CPY    #ID_BRIDGE        ; 2             don't move bridge, house and fuel
       BCS    .skipMoveEnemy    ; 2
       LDA    frameCnt          ; 3
       ROR                      ; 2
       BCS    .skipMoveEnemy    ; 2             move helicopter and ship every 2nd frame
       LDA    zoneLst,X         ; 4
       ASL                      ; 2             enemy moving? (test #ENEMY_MOVE_FLAG)
       BPL    .skipMoveEnemy    ; 2              no, skip move
       ASL                      ; 2             enemy collided with PF? (test #PF_COLLIDE_FLAG)
       BPL    .noPFCollision    ; 2              no, skip
       ASL                      ; 2             enemy changed dir last frame? (test #DIR_CHANGE_FLAG)
       BMI    .xMoveEnemy       ; 2              yes, skip direction change
       LDA    State1Lst,X       ; 4             change
       EOR    #DIRECTION_FLAG   ; 2              enemy movement
       STA    State1Lst,X       ; 4              direction
       LDA    zoneLst,X         ; 4             set the direction-change flag
       ORA    #DIR_CHANGE_FLAG  ; 2              otherwise, ship collides with sloped bank
       BNE    .endChangeDir     ; 2              on flip and gets stuck in flip loop

.noPFCollision:
       LDA    zoneLst,X         ; 4
       AND    #~DIR_CHANGE_FLAG ; 2             clear the direction-change flag
.endChangeDir:
       STA    zoneLst,X         ; 4

; move enemy one pixel left or right:
; (no real position variables, the code is working
;  directly  with the positioning values)
.xMoveEnemy:
       LDY    XPos1Lst,X        ; 4
       LDA    State1Lst,X       ; 4
       LSR                      ; 2
       LSR                      ; 2
       LSR                      ; 2
       LSR                      ; 2
       EOR    #$07              ; 2
       BCS    .xMoveLeft        ; 2             moving left!
       ADC    #1                ; 2
       CMP    #15               ; 2
       BCC    .skipRightIny     ; 2
       SBC    #15               ; 2
       INY                      ; 2
.skipRightIny:
       CPY    #10               ; 2
       BCC    .contMoveX        ; 2
       CMP    #10               ; 2             >= 160?
       BCC    .contMoveX        ; 2              no, continue
       LDY    #0                ; 2              yes,..
       TYA                      ; 2              ..move shape (plane)..
       BEQ    .contMoveX        ; 2              ..to the very left (0)

.xMoveLeft:
       SBC    #1                ; 2
       BCS    .contMoveX2       ; 2
       ADC    #15               ; 2
       DEY                      ; 2             < 0?
       BPL    .contMoveX        ; 2              no, continue
       LDY    #10               ; 2              yes, move shape (plane)..
       LDA    #9                ; 2              ..to the very right (159)
.contMoveX:
       STY    XPos1Lst,X        ; 4             store coarse value here
.contMoveX2:
       EOR    #$07              ; 2
       JSR    Mult16            ; 6
       EOR    State1Lst,X       ; 4
       AND    #FINE_MASK        ; 2             #$F0
       EOR    State1Lst,X       ; 4
       STA    State1Lst,X       ; 4             OR fine value into here
.skipMoveEnemy:

; clear PF-collision:
       LDA    zoneLst,X         ; 4
       AND    #~PF_COLLIDE_FLAG ; 2
       STA    zoneLst,X         ; 4
       DEX                      ; 2
       BMI    .exitLoopEnemies  ; 2
       JMP    .loopEnemies      ; 3
.exitLoopEnemies:

; *** read joystick: ***
       LDA    SWCHA             ; 4  $F572
       LDX    player            ; 3
       BEQ    .player1          ; 2
       JSR    Mult16            ; 6
.player1:
       AND    #$F0              ; 2             mask out other player joystick
       TAX                      ; 2
       LDY    #4                ; 2
.loopBits:
       ROL                      ; 2             roll new 4 bits into joystick
       ROL    joystick          ; 5              (old 4 bits got into upper nibble!)
       DEY                      ; 2
       BNE    .loopBits         ; 2

       CPX    #$F0              ; 2
       BNE    .joystickMoved    ; 2
       LDX    player            ; 3
       LDA    INPT4-$30,X       ; 4
       BMI    .noFire           ; 2

.joystickMoved:
       LDA    gameMode          ; 3             joystick moved and/or button pressed
       CMP    #SCROLL_STOP      ; 2             at the scroll stop of a level start?
       BNE    .skipLevelStart   ; 2              no, continue play
       LDA    #64               ; 2              yes
       STA    speedY            ; 3             set jet speed at minimum of 64
       STY    gameMode          ; 3             y=0! start level

.skipLevelStart:
  IF SCREENSAVER
       STY    SS_Delay          ; 3             y=0!
  ELSE
       FILL_NOP 2
  ENDIF

.noFire:
       LDX    gameMode          ; 3  $F59F      game running?
       BEQ    .checkCollisions  ; 2              yes, jump to collision checking
       BMI    .jetExplosion     ; 2             if still in jet explosion time jump to jet explosion
       CPX    #SCROLL_STOP+1    ; 2             done scrolling into first/restart level? (if gameMode < SCROLL_STOP+1)
       BCC    .doSoundJmp       ; 2              yes, done, jump to sound (gameMode < SCROLL_STOP+1)
       BNE    .contScroll       ; 2             else if (gameMode > SCROLL_STOP+1) continue scrolling
; decrease lives:                               else if (gameMode == SCROLL_STOP+1) last frame before scroll stop:
       LDA    livesPtr          ; 3             load lives pointer (0 = boot mode; 88 = new game/game over; 89 = last life; lives * 8)
       BEQ    .finishGame       ; 2             if 0 jump to end game (used at boot to stay in select mode)
       SBC    #DIGIT_H          ; 2             is last life? (lives - 8, the height of score digits)
       BNE    .checkNewGame     ; 2              no, check for max lives
       LDA    #<Copyright0      ; 2              yes, don't display life count of 0 and move ptr to copyright sprite (a = $59, 89)
.checkNewGame:
       CMP    #<ExclamationPt   ; 2             is this a new game? (lives = $50, 80)
       BNE    .saveLivesPtr     ; 2              no, jump to store the current life or copyright pointer
       LDA    #<Three           ; 2              yes, reset lives ptr to "3" sprite (a = $18, 24)
.saveLivesPtr:
       STA    livesPtr          ; 3
.contScroll:
       DEC    gameMode          ; 5             continue the scroll countdown towards SCROLL_STOP
       BNE    .doSoundJmp       ; 2

.jetExplosion:
       INX                      ; 2
       BEQ    .doSoundJmp       ; 2
       DEC    gameMode          ; 5             still in jet explosion time?
       BMI    .doSoundJmp       ; 2              yes, jump to sound
       STY    shapePtr0         ; 3              no, check other player
       LDA    livesPtr2         ; 3
       CMP    #<Copyright0      ; 2             other player still alive?
       BEQ    .skipSwap         ; 2              no, skip swap
       JSR    SwapPlayers       ; 6
.skipSwap:
       LDA    livesPtr          ; 3
       CMP    #<Copyright0      ; 2             current player still alive?
       BNE    .initPlayer       ; 2              yes, continue
.finishGame:
       JSR    FinishGame        ; 6
       BNE    .doSoundJmp       ; 2

.initPlayer:
       LDX    #shapePtr0+2-PF1Lst;2             #22, counter to fill 23 bytes from PF1Lst to newBankWidth...
       JSR    GameInit          ; 6              when this is called
       TYA                      ; 2
       ORA    #PF_ROAD_FLAG     ; 2
       STA    zoneLstNew        ; 3
       LDA    randomLoSave      ; 3             load..
       STA    randomLo          ; 3             ..random variables..
       LDA    randomHiSave      ; 3             ..with saved..
       STA    randomHi          ; 3             ..player variables
.doSoundJmp:
       JMP    DoSound           ; 3

.checkCollisions:
       LDX    collidedEnemy     ; 3             collided with enemy?
       BMI    .endCollisions    ; 2              no, skip
       LDA    Shape1IdLst,X     ; 4
       CMP    #ID_PLANE         ; 2             collided with explosion?
       BCC    .endCollisions    ; 2              no, skip
       CMP    #ID_BRIDGE        ; 2             collided with ship, plane or helicopter?
       BCC    .noBridge         ; 2              yes, do collision
       BNE    .refuel           ; 2              no, collided with fuel!
       INC    levelEnd          ; 5              no, collided with bridge!
.noBridge:
       LDY    #$1F              ; 2             load some sound values
       LDA    #1                ; 2             sound id = 1
       JSR    LoseJet           ; 6
       LDX    collidedEnemy     ; 3
       LDA    #ID_EXPLOSION2    ; 2             start explosion
       JMP    .contJetExplosion ; 3

.refuel:
       LDA    fuelHi            ; 3
       ADC    #$01              ; 2             refuel at rate of $0100/frame
       LDX    #4                ; 2             sound id = 4
       BCC    .notFull          ; 2
       LDA    #$FF              ; 2             fuel maxed: if fuel > $FFFF, set it to $FFFF
       STA    fuelLo            ; 3
       LDX    #3                ; 2             sound id = 3
.notFull:
       STA    fuelHi            ; 3
       CPX    sound0Id          ; 3
       BEQ    .endCollisions    ; 2
       STX    sound0Id          ; 3
       LDA    #$08              ; 2
       STA    sound0Cnt         ; 3

.endCollisions:
       LDX    PFCrashFlag       ; 3             jet crashed?
       BMI    .skipCrash        ; 2              no, skip
.maxedOut:
       LDY    #$1F              ; 2
       LDA    #1                ; 2             sound id = 1
.loseJet:
       JSR    LoseJet           ; 6
       BNE    .doSoundJmp       ; 2

.skipCrash:

; decrease fuel:
       LDA    fuelLo            ; 3
       SEC                      ; 2
  IF TRAINER
       SBC    #0
  ELSE
       SBC    #$20              ; 2             burn fuel at rate of $0020/frame
  ENDIF
       BCS    .skipDecHi        ; 2             branch if fuelLo >= 0
       LDY    fuelHi            ; 3
       BNE    .fuelOk           ; 2             branch if fuelHi > 0 (ie: can be borrowed from)
       LDA    #2                ; 2             sound id = 2
       LDY    #$23              ; 2
       JMP    .loseJet          ; 3             out of fuel!

.fuelOk:
       DEC    fuelHi            ; 5
.skipDecHi:
       STA    fuelLo            ; 3

; *** move jet left or right: ***
       LDA    joystick          ; 3  $F650
       TAY                      ; 2             store joystick in Y
       AND    #MOVE_RIGHT|MOVE_LEFT; 2          %1000 | $0100
       EOR    #MOVE_RIGHT|MOVE_LEFT; 2          %1000 | $0100
       BNE    .moveHorizontal   ; 2
       STA    speedX            ; 3             jet is flying straight
       STA    triggerX          ; 3             speedX=triggerX=0
       LDX    #<JetStraight-1   ; 2
       BNE    .setPtr0          ; 2

.moveHorizontal:
       LDA    speedX            ; 3             increase the x speed change
       CLC                      ; 2
       ADC    #8                ; 2             A = speedX + 8
       BCS    .maxSpeed         ; 2             branch if speedX+8 > 255
       STA    speedX            ; 3             store new speedX if less than max (248..255)
.maxSpeed:
       LDX    #<JetMove-1       ; 2
       TYA                      ; 2             A = joystick
       AND    #MOVE_RIGHT       ; 2             %1000 (MJJ: AND with MOVE_RIGHT means left because 0 means on)
       STA    reflect0          ; 3
       BEQ    .moveRight        ; 2             branch if right (speedX at max or not)
       BCS    .maxLeftSpeed     ; 2             branch if left and speedX at max
       LDA    triggerX          ; 3              left, but speedX < max
       SEC                      ; 2
       SBC    speedX            ; 3             A = triggerX - speedX
       BCS    .shiftTriggerX    ; 2             de-accumulate speedX until it triggers < 0
.maxLeftSpeed:
       DEC    playerX           ; 5             move player left 1 pix if speedX at max or triggerX went below 0
       BNE    .shiftTriggerX    ; 2             (A = 248 when starting from speedX 0, 8 at max speed)
; For example, holding left after center, move when triggerX passes below 0:
; triggerX-speedX = 0-8 [move]
; = 248-16 = 232-24 = 208-32 = 176-40 = 136-48 = 88-56 = 32-64 [move]
; = 224-72 = 152-80 = 72-88 [move]
; = 240-96 = 144-104 = 40-112 [move]
; = 184-120 = 64-128 [move]
; = 192-136 = 56-144 [move]
; = 168-152 = 16-160 [move]
; = 112-168 [move]
; = 200-176 = 24-184 [move]
; = 96-192 [move]
; = 160-200 [move]
; = 216-208 = 8-216 [move]
; = 48-224 [move]
; = 80-232 [move]
; = 104-240 [move] = 120
; speedX at max (248..255) [move] triggerX=128
; speedX at max (248..255) [move] triggerX=8
; speedX at max (248..255) [move] triggerX=8...
; ...
; So, basically:
;   Move sideways 1 pix on first frame of command,
;   skip 6 frames then move (7th frame after first),
;   skip 2 frames then move,
;   skip 2, move,
;   skip 1, move,
;   skip 1, move,
;   skip 1, move,
;   move,
;   skip 1, move,
;   move,
;   move,
;   skip 1, move,
;   move, move, move...

; (MJJ: Why not use the same code for both directions? Dunno.
;  Oversight during refactoring is my only guess.
;  Or, I can't see the forest for the trees.)

.moveRight:
       BCS    .maxRightSpeed    ; 2             branch if right and speedX at max
       LDA    triggerX          ; 3              right, but speedX < max
       BIT    joystick          ; 3             moved right before or triggerX < 128?
       BPL    .wasRightOrAtSpeed; 2              yes, skip (more or less allows direction flip at same speedX)
       LDA    #255              ; 2              no, ensure one instant move right
.wasRightOrAtSpeed:
       ADC    speedX            ; 3             A = triggerX + speedX
       BCC    .shiftTriggerX    ; 2             accumulate speedX until it triggers > 255
.maxRightSpeed:
       INC    playerX           ; 5             move player right 1 pix if speedX at max or triggerX went above 255
; For example, holding right after center, move when triggerX passes above 255:
; triggerX-speedX = 255+8 [move]
; = 7+16 = 23+24 = 47+32 = 79+40 = 119+48 = 167+56 = 223+64 [move]
; = 31+72 = 103+80 = 183+88 [move]
; = 15+96 = 111+104 = 215+112 [move]
; = 71+120 = 191+128 [move]
; = 63+136 = 199+144 [move]
; = 87+152 = 239+160 [move]
; = 143+168 [move]
; = 55+176 = 231+184 [move]
; = 159+192 [move]
; = 95+200 [move]
; = 39+208 = 247+216 [move]
; = 207+224 [move]
; = 175+232 [move]
; = 151+240 [move] = 135
; speedX at max (248..255) [move] triggerX=127
; speedX at max (248..255) [move] triggerX=0
; speedX at max (248..255) [move] triggerX=0...
; ...

.shiftTriggerX:
       STA    triggerX          ; 3
.setPtr0:
       STX    shapePtr0         ; 3

; change jet speed:
       LDX    speedY            ; 3  $F694      X = speedY
       TYA                      ; 2             A = joystick
       LSR                      ; 2             up: 1110 >> x111 CF=0; is joystick up?
       BCS    .checkDown        ; 2              no, branch to check down
.incSpeedY:
       TXA                      ; 2             A = speedY
       ADC    #2                ; 2             A = speedY + 2; is A <= 254?
       BCC    .storeSpeedY      ; 2              yes, store the new speed
       BCS    .skipChange       ; 2              no, speed maxed out

.checkDown:
       LSR                      ; 2             down: 1101 >> >> xx11 CF=0; is joystick down?
       BCC    .decSpeedY        ; 2              yes, branch to decrease speed
       TXA                      ; 2              no, return to cruise speed if below it
       ASL                      ; 2             is speedY < 128?
       BCC    .incSpeedY        ; 2              yes, increase it
       BEQ    .skipChange       ; 2              speedY == 128, branch to keep it there
                                ;                speedY > 128, decrease it
.decSpeedY:
       TXA                      ; 2             A = speedY
       CMP    #65               ; 2             is speedY < 65?
       BCC    .skipChange       ; 2              yes, speed at minimum
       SBC    #2                ; 2              no, A = speedY - 2
.storeSpeedY:
       STA    speedY            ; 3             store the new speed
.skipChange:

       LDX    hitEnemyIdx       ; 3             object hit?
       BMI    .skipCollisions   ; 2              no, skip
       LDY    Shape1IdLst,X     ; 4
       CPY    #ID_PLANE         ; 2             enemy objects?
       BCC    .skipCollisions   ; 2              no, explosions
       LDA    #ID_EXPLOSION1    ; 2             start explosion animation
.contJetExplosion:
       LDY    Shape1IdLst,X     ; 4
       STA    Shape1IdLst,X     ; 4
       LDA    #23               ; 2
       STA    bridgeSound       ; 3
       CPY    #ID_BRIDGE        ; 2
       BNE    .skipBridge       ; 2
       STA    bridgeExplode     ; 3             start bridge explosion
       LDA    #$E0|TWO_COPIES   ; 2             set fixed position and size (two copies close)
       STA    State1Lst,X       ; 4
       LDA    #4                ; 2             coarse positiong value
       STA    XPos1Lst,X        ; 4
       INC    levelEnd          ; 5             new level has been started
.skipBridge:

; increase score:
       LDX    #8                ; 2             add 10s
       LDA    ScoreTab,Y        ; 4
       BPL    .loopSetPtr1      ; 2
       AND    #$7F              ; 2             add n*100 points
       LDX    scorePtr1+8       ; 3
       CPX    #<Space           ; 2
       BNE    .noSpace          ; 2
       LDX    #<Zero            ; 2             replace Space..
       STX    scorePtr1+8       ; 3             ..with Zero
.noSpace:
       LDX    #6                ; 2             add 100s
.loopSetPtr1:
       PHA                      ; 3
       CPX    #2                ; 2             life pointer
       BNE    .notLivePtr       ; 2
; check for bonus life:
       LDA    livesPtr          ; 3
       CMP    #<Nine            ; 2
       BEQ    .maxLives         ; 2
       BCC    .notMax           ; 2
       LDA    #$FF              ; 2             CF=1!
.notMax:
       ADC    #DIGIT_H          ; 2
       STA    livesPtr          ; 3
.maxLives:
.notLivePtr:
       LDA    scorePtr1,X       ; 4
       SEC                      ; 2
       SBC    #<Space           ; 2
       BNE    .noSpace2         ; 2
       STA    scorePtr1,X       ; 4             point to '0'
.noSpace2:
       PLA                      ; 4
       CLC                      ; 2
       ADC    scorePtr1,X       ; 4
       CMP    #<ExclamationPt   ; 2
       BCC    .noMaxOut         ; 2             exit loop
       SBC    #<ExclamationPt   ; 2
       STA    scorePtr1,X       ; 4
       LDA    #DIGIT_H          ; 2
       DEX                      ; 2
       DEX                      ; 2
       BPL    .loopSetPtr1      ; 2

; more than 999990 points, set score to !!!!!!, game over:
       LDA    #<ExclamationPt   ; 2
       LDX    #12-2             ; 2
       JSR    SetScorePtr1      ; 6
       LDA    #<Copyright0      ; 2
       STA    livesPtr          ; 3
       JMP    .maxedOut         ; 3

.noMaxOut:
       STA    scorePtr1,X       ; 4
.noMissile:
       LDX    #$B4              ; 2             disable missile
       BNE    .directMissile    ; 2
.skipCollisions:

; *** move or fire missiles: ***
       LDA    missileFlag       ; 3
       BPL    .noMissile        ; 2
       LDA    missileY          ; 3
       CMP    #MAX_MISSILE+1    ; 2
       BCS    .checkFire        ; 2
       ADC    #MISSILE_SPEED    ; 2             y-move missile
       TAX                      ; 2
       LDA    SWCHB             ; 4             read difficulty
       LDY    player            ; 3
       BNE    .player1a         ; 2
       ASL                      ; 2
.player1a:
       TAY                      ; 2
       BPL    .guidedMissile    ; 2
       BMI    .directMissile    ; 2

.checkFire:
       LDX    player            ; 3
       LDA    INPT4-$30,X       ; 4
       BMI    .noMissile        ; 2
       LDX    #$0F              ; 2
       STX    missileSound      ; 3
       LDX    #MIN_MISSILE      ; 2
.guidedMissile:
       LDA    playerX           ; 3
       CLC                      ; 2
       ADC    #$05              ; 2
       STA    missileX          ; 3
.directMissile:
       STX    missileY          ; 3

