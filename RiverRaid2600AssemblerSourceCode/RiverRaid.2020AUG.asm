NextRandom16 SUBROUTINE
; implements a 16 bit LFSR which generates a new random number:
       LDA    randomHi          ; 3             MJJ: setup for randomizing the Carry bit
       ASL                      ; 2             MJJ:   ditto
       ASL                      ; 2             MJJ:   ditto
       ASL                      ; 2             MJJ:   ditto
       EOR    randomHi          ; 3             MJJ:   ditto
       ASL                      ; 2             MJJ: sets Carry bit for next ROL
       ROL    randomLo          ; 5             MJJ: changes randomLo, sets Carry bit for next ROL
       ROL    randomHi          ; 5             MJJ: changes randomHi
       RTS                      ; 6
; (JTZ: randomHi is very random, randomLo is NOT when more than one bit is used,
; because: randomLo[x+1] = randomLo[x]*2 + 0/1, but randomLo is used more often,
; randomHi only for new enemy and which. This could make the game a bit predictable.)
;
; MJJ: I don't see this the same as JTZ.  Both bytes get randomized with a fairly
; randomish carry bit in a 16-bit ROL and are thus equal in randomness strength.
; I can only assume JTZ read the EOR the wrong way as writing to the address
; instead of the the accumulator.  Also, much of the code reads only various bits
; or nibbles from these 16 bits so it makes sense to rotate them as a 16-bit chunk
; [like is done here] and not think of them as one byte versus the other.
; Some observations, for example:
;
; /--hi--\/--lo--\
; 0000111100001111
;           [][__]
;            |  |
;            |   `-- bank width
;             `----- non-island/island banks toggle
;
;         ,--------- obj mirrored or not on straights, left or right side on jaggeds
;         |     ,--- river obj x-pos on straight levels
;         |  ___|
;         | [    ]
; 0000111100001111
; [______] | [___]
;       |  |    | 
;       |  |     `-- house x-pos on straight levels
;       |   `------- fuel or house
;        `---------- new sprite odds: enemy vs fuel/house
;
