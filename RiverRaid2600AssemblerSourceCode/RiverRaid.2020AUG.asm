GetPageFlag SUBROUTINE
; INPUT:  X = bank width
; RETURN: A = 0 or 1 (PF1_PAGE_FLAG)
;             bank width 0   : return 0
;             bank width 1-8 : return PF1_PAGE_FLAG
;             bank width 9-14: return 0
; Ultimately used to set a flag in zoneLst that indicates whether the river bank
; pattern will be found in page $FCxx or $FDxx (because the pointer vars only store
; the lo byte and not the hi byte, thus, one more bit is needed somewhere).
       TXA                      ;2              copy X to A
       BEQ    .exit             ;2              if bank width = 0, exit with 0 (pattern will be in the $FC page)
       LDA    #0                ;2
       CPX    #SWITCH_PAGE_ID   ;2              compare bank width to 9   (X - 9)
       BCS    .exit             ;2              if bank width >= 9, exit with 0 (pattern will be in the $FC page)
       LDA    #PF1_PAGE_FLAG    ;2               else exit with 1 (pattern will be in the $FC+1 page)
.exit:
       RTS                      ;6
